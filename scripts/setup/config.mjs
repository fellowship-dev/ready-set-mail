// The installer's local Wrangler config: generated from the tracked wrangler.jsonc, git-ignored,
// and picked up by `npm run deploy`, `npm run migrate` and `npm run wrangler` (scripts/wrangler.mjs).
// The tracked file is never edited, so `git pull` stays clean.

export const TRACKED_CONFIG = 'wrangler.jsonc';
export const LOCAL_CONFIG = 'wrangler.local.jsonc';
export const KV_SUFFIX = '-oauth';

/** JSON with comments and trailing commas -> value. Strings are left untouched. */
export function parseJsonc(text) {
  let out = '';
  let i = 0;
  while (i < text.length) {
    const c = text[i];
    if (c === '"') {
      let j = i + 1;
      while (j < text.length && text[j] !== '"') j += text[j] === '\\' ? 2 : 1;
      out += text.slice(i, j + 1);
      i = j + 1;
    } else if (c === '/' && text[i + 1] === '/') {
      while (i < text.length && text[i] !== '\n') i++;
    } else if (c === '/' && text[i + 1] === '*') {
      const end = text.indexOf('*/', i + 2);
      i = end < 0 ? text.length : end + 2;
    } else {
      out += c;
      i++;
    }
  }
  // Trailing commas, outside strings (strings were copied verbatim, so match them and keep them).
  out = out.replace(/"(?:[^"\\]|\\.)*"|,(\s*[}\]])/g, (m, tail) => (tail !== undefined ? tail : m));
  return JSON.parse(out);
}

/** The names one instance uses. One name in, three resource names out. */
export function resourceNames(name) {
  return { worker: name, d1: name, kv: `${name}${KV_SUFFIX}` };
}

/** https://<worker>.<subdomain>.workers.dev */
export function workersDevUrl(worker, subdomain) {
  if (!subdomain) throw new Error('workersDevUrl: no subdomain');
  return `https://${worker}.${subdomain}.workers.dev`;
}

/**
 * The local config for one installation: the tracked config with this installation's name, ids,
 * origin and account, workers.dev serving on (off when the account has none) and preview URLs off. Throws when the tracked config
 * no longer has the shape this depends on, rather than writing a config that deploys the wrong thing.
 */
/** Rate-limit binding names in wrangler.jsonc, in order. */
export function ratelimitBindings(cfg) {
  return (cfg.unsafe?.bindings ?? []).filter(b => b.type === 'ratelimit');
}

/**
 * First of this instance's rate-limit namespace ids. Cloudflare keys a rate-limit counter by its
 * namespace_id within the account, so two installs with the repository's 1001-1006 would share counters.
 * Deterministic from the name (stable across resumes and upgrades), in steps of 10, from 10000 up.
 */
export function ratelimitBase(name) {
  let h = 2166136261;
  for (const ch of name) { h ^= ch.charCodeAt(0); h = Math.imul(h, 16777619) >>> 0; }
  return 10000 + (h % 99000) * 10;
}

/** The first base at or after `start` whose block of `count` ids misses every id in `used`. */
export function freeRatelimitBase(start, count, used) {
  let base = start;
  while ([...Array(count).keys()].some(i => used.has(String(base + i)))) base += 10;
  return base;
}

export function generateLocalConfig(tracked, { name, accountId, d1Id, kvId, url, workersDev = true, ratelimitBase: rlBase = null }) {
  const cfg = structuredClone(tracked);
  const names = resourceNames(name);
  const d1 = (cfg.d1_databases ?? []).filter(d => d.binding === 'DB');
  const kv = (cfg.kv_namespaces ?? []).filter(k => k.binding === 'OAUTH_KV');
  if (d1.length !== 1 || kv.length !== 1) throw new Error(`${TRACKED_CONFIG} must declare exactly one DB (D1) and one OAUTH_KV (KV) binding`);
  cfg.name = names.worker;
  cfg.account_id = accountId;
  d1[0].database_name = names.d1;
  d1[0].database_id = d1Id;
  kv[0].id = kvId;
  // Set here, not in the tracked file, so an existing instance on its own domain never gains a workers.dev address by copying it.
  cfg.workers_dev = workersDev;
  cfg.preview_urls = false;
  cfg.vars = { ...(cfg.vars ?? {}), WORKER_NAME: names.worker, BETTER_AUTH_URL: url };
  if (rlBase !== null) ratelimitBindings(cfg).forEach((b, i) => { b.namespace_id = String(rlBase + i); });
  // `npm run deploy` builds the dashboard before migrating; Wrangler's own build hook would build it a second time.
  delete cfg.build;
  return cfg;
}

export function renderLocalConfig(cfg, { name }) {
  return `// Generated by \`npm run setup\` for the instance "${name}". Not tracked by git.\n`
    + '// `npm run deploy`, `npm run migrate` and `npm run wrangler -- …` use this file when it exists.\n'
    + '// To change shared settings, edit wrangler.jsonc and run `npm run setup -- --resume --name ' + name + '` to regenerate it.\n'
    + JSON.stringify(cfg, null, '\t') + '\n';
}

/** Which installation a local config belongs to: { name, d1Id, kvId } or null if it is not ours. */
export function describeLocalConfig(text) {
  try {
    const cfg = parseJsonc(text);
    return {
      name: cfg.name,
      d1Id: cfg.d1_databases?.find(d => d.binding === 'DB')?.database_id ?? null,
      kvId: cfg.kv_namespaces?.find(k => k.binding === 'OAUTH_KV')?.id ?? null,
    };
  } catch {
    return null;
  }
}

/** Placeholder ids still in place: a deploy or remote command with this config would fail. */
export function hasPlaceholders(cfg) {
  return [...(cfg.d1_databases ?? []).map(d => d.database_id), ...(cfg.kv_namespaces ?? []).map(k => k.id)]
    .some(id => typeof id === 'string' && id.startsWith('REPLACE_WITH_'));
}

/** What each cron in wrangler.jsonc does (src/cron.ts). Unknown expressions are listed without a description. */
export const CRON_DESCRIPTIONS = {
  '0 4 * * *': 'daily 04:00 UTC: data lifecycle (retry Cloudflare revocations, then retention sweeps)',
  '0 8 * * *': 'daily 08:00 UTC: re-reads each domain\'s DNS, runs monitor checks and change alerts',
  '0 9 * * 1': 'Mondays 09:00 UTC: weekly DMARC digest email',
  '0 10 * * *': 'daily 10:00 UTC: SPF flattening refresh (only for domains that turned it on)',
  '0 11 * * *': 'daily 11:00 UTC: usage heartbeat, sent only if you opt in to telemetry',
};

export function describeCrons(cfg) {
  return (cfg.triggers?.crons ?? []).map(c => ({ cron: c, what: CRON_DESCRIPTIONS[c] ?? 'see docs/self-hosting.md' }));
}
